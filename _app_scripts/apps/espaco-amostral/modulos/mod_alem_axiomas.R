texto_alem_axiomas <- function() {
  tr(
    shiny::withMathJax(
      shiny::p(
        "Em espaços amostrais finitos ou enumeráveis, é sempre possível atribuir probabilidade a todos os",
        "\\(2^n\\) subconjuntos de \\(S\\) sem contradição (Casella e Berger, Ex. 1.2.2). Em espaços contínuos como",
        "\\(S = (-\\infty, \\infty)\\), contudo, tentar medir absolutamente qualquer subconjunto choca-se com",
        "conjuntos patológicos quando se exige invariância por translação. Por essa razão, os axiomas de Kolmogorov",
        "definem \\(P\\) sobre uma \\(\\sigma\\)-álgebra \\(\\mathcal{B}\\) (Def. 1.2.1): uma família de eventos que",
        "(1) contém \\(\\varnothing\\), (2) é fechada no complemento e (3) é fechada em uniões enumeráveis — na reta",
        "real, a \\(\\sigma\\)-álgebra de Borel gerada pelos intervalos \\([a, b]\\) (Ex. 1.2.3). Além disso, o",
        "Axioma 3 pede aditividade enumerável, mais forte do que a aditividade finita defendida por de Finetti",
        "(1972): sem passar ao limite em uniões infinitas, teoremas centrais de convergência da inferência deixariam",
        "de valer na forma usual."
      ),
      shiny::p(
        "Quando não se conhece a estrutura de dependência entre eventos \\(A_1, \\dots, A_k\\), os axiomas ainda",
        "fornecem cotas universais a partir das probabilidades marginais \\(P(A_i)\\). Pela desigualdade de Boole",
        "(Teo. 1.2.11b), a probabilidade da união nunca supera a soma individual,",
        "\\(P\\!\\left(\\bigcup_{i=1}^k A_i\\right) \\le \\sum_{i=1}^k P(A_i)\\). Aplicada aos complementares, a",
        "mesma desigualdade vira a cota de Bonferroni (eq. 1.2.10),",
        "\\(P\\!\\left(\\bigcap_{i=1}^k A_i\\right) \\ge \\sum_{i=1}^k P(A_i) - (k - 1)\\). Com",
        "\\(P(A) = P(B) = 0{,}95\\), a interseção tem probabilidade de pelo menos \\(0{,}90\\) (Ex. 1.2.10), seja qual",
        "for a dependência entre os eventos. É por isso que dois intervalos de confiança de 95% acertam juntos em pelo",
        "menos 90% das amostras. Se as probabilidades individuais não forem grandes, a cota pode ficar negativa:",
        "correta, mas inútil."
      ),
      shiny::p(
        "Caso as interseções duas a duas, três a três e assim por diante sejam conhecidas, a identidade de",
        "inclusão-exclusão (Casella e Berger, seção 1.8.1) recupera o valor exato da união somando e descontando",
        "sobreposições sucessivas: definindo \\(P_1 = \\sum_i P(A_i)\\), \\(P_2 = \\sum_{i<j} P(A_i \\cap A_j)\\),",
        "\\(P_3 = \\sum_{i<j<l} P(A_i \\cap A_j \\cap A_l)\\), vale",
        "\\(P\\!\\left(\\bigcup_{i=1}^k A_i\\right) = P_1 - P_2 + P_3 - \\dots + (-1)^{k+1} P_k\\). Truncar essa",
        "soma num termo ímpar entrega uma cota superior (a começar por Boole, \\(P_1\\)), enquanto truncar num termo",
        "par entrega uma cota inferior (\\(P_1 - P_2\\), \\(P_1 - P_2 + P_3 - P_4\\)), cercando o valor verdadeiro."
      ),
      shiny::p(
        shiny::strong("Experimente:"),
        "teste as coleções candidatas em \\(S = \\{1, 2, 3\\}\\) para ver exatamente qual propriedade de fechamento",
        "quebra nas coleções inválidas; depois varie \\(k\\), \\(p = P(A_i)\\) e o regime de dependência para",
        "acompanhar a oscilação das somas parciais \\(S_m\\) e o momento em que a cota de Bonferroni cruza zero."
      )
    ),
    shiny::withMathJax(
      shiny::p(
        "On finite or countable sample spaces, every one of the \\(2^n\\) subsets of \\(S\\) can be assigned a",
        "probability without contradiction (Casella and Berger, Ex. 1.2.2). On uncountable spaces such as",
        "\\(S = (-\\infty, \\infty)\\), however, attempting to measure every arbitrary subset runs into pathological",
        "sets once translation invariance is required. Kolmogorov's axioms therefore define \\(P\\) on a",
        "\\(\\sigma\\)-algebra \\(\\mathcal{B}\\) (Def. 1.2.1): a collection of subsets that (1) contains",
        "\\(\\varnothing\\), (2) is closed under complements and (3) is closed under countable unions — on the real",
        "line, the Borel \\(\\sigma\\)-algebra generated by intervals \\([a, b]\\) (Ex. 1.2.3). Axiom 3 also assumes",
        "countable additivity rather than de Finetti's (1972) finite additivity, since taking limits across",
        "countable sequences of events underpins modern statistical limit theory."
      ),
      shiny::p(
        "When the dependence structure among \\(A_1, \\dots, A_k\\) is unknown, the axioms still bound joint and",
        "union probabilities from the marginals \\(P(A_i)\\) alone. By Boole's inequality (Thm. 1.2.11b),",
        "\\(P\\!\\left(\\bigcup_{i=1}^k A_i\\right) \\le \\sum_{i=1}^k P(A_i)\\). Applying Boole to the complements",
        "produces Bonferroni's inequality (eq. 1.2.10),",
        "\\(P\\!\\left(\\bigcap_{i=1}^k A_i\\right) \\ge \\sum_{i=1}^k P(A_i) - (k - 1)\\). With",
        "\\(P(A) = P(B) = 0.95\\), the intersection has probability at least \\(0.90\\) (Ex. 1.2.10), whatever the",
        "dependence between the events. That is why two 95% confidence intervals are jointly right in at least 90%",
        "of samples. When the individual probabilities are not large, the bound can turn negative: true, but useless."
      ),
      shiny::p(
        "When pairwise, triple and higher-order intersections are available, the inclusion-exclusion identity",
        "(Casella and Berger, section 1.8.1) recovers the exact probability of the union: writing",
        "\\(P_1 = \\sum_i P(A_i)\\), \\(P_2 = \\sum_{i<j} P(A_i \\cap A_j)\\),",
        "\\(P_3 = \\sum_{i<j<l} P(A_i \\cap A_j \\cap A_l)\\), one obtains",
        "\\(P\\!\\left(\\bigcup_{i=1}^k A_i\\right) = P_1 - P_2 + P_3 - \\dots + (-1)^{k+1} P_k\\). Stopping at an",
        "odd step yields an upper bound (starting with Boole's \\(P_1\\)), whereas stopping at an even step yields a",
        "lower bound (\\(P_1 - P_2\\), \\(P_1 - P_2 + P_3 - P_4\\)), bracketing the true union probability."
      ),
      shiny::p(
        shiny::strong("Try it:"),
        "switch across candidate collections on \\(S = \\{1, 2, 3\\}\\) to see which closure axiom breaks in the",
        "invalid families; then adjust \\(k\\), \\(p = P(A_i)\\) and the dependence regime to watch the partial sums",
        "\\(S_m\\) oscillate around \\(P(\\bigcup A_i)\\) and see when Bonferroni's bound crosses zero."
      )
    )
  )
}

cuidados_alem_axiomas <- function() {
  tr(
    c(
      "Bonferroni negativa" = paste(
        "se k = 5 e P(Aᵢ) = 0,70, a fórmula dá 5(0,70) − 4 = −0,50. A desigualdade P(⋂ Aᵢ) ≥ −0,50 continua",
        "matematicamente verdadeira, mas não acrescenta nada ao Axioma 1 (P ≥ 0)."
      ),
      "Oscilação das somas parciais" = paste(
        "o termo P_m vale C(k, m) p^m sob independência e C(k, m) p sob sobreposição total. No segundo caso, ele",
        "cresce antes de diminuir (com k = 4 e p = 0,5, P₁ = 2 e P₂ = 3), ao contrário da afirmação da seção 1.8.1",
        "de que P_i ≥ P_j para i ≤ j. As somas parciais podem passar longe de [0, 1], mas as cotas continuam valendo:",
        "acima de P(⋃ Aᵢ) nos passos ímpares e abaixo nos pares."
      ),
      "Boole e Bonferroni são a mesma desigualdade" = paste(
        "aplicar Boole a A₁ᶜ, …, Aₖᶜ e usar De Morgan transforma P(⋃ Aᵢᶜ) ≤ Σ(1 − P(Aᵢ)) exatamente em",
        "P(⋂ Aᵢ) ≥ Σ P(Aᵢ) − (k − 1) (Casella e Berger, eq. 1.2.10)."
      )
    ),
    c(
      "Negative Bonferroni bounds" = paste(
        "with k = 5 and P(Aᵢ) = 0.70, the formula gives 5(0.70) − 4 = −0.50. The statement P(⋂ Aᵢ) ≥ −0.50 remains",
        "true, yet adds nothing beyond Axiom 1 (P ≥ 0)."
      ),
      "Swings in the partial sums" = paste(
        "the term P_m equals C(k, m) p^m under independence and C(k, m) p under complete overlap. In the second case",
        "it grows before it shrinks (with k = 4 and p = 0.5, P₁ = 2 and P₂ = 3), contrary to the claim in section 1.8.1",
        "that P_i ≥ P_j for i ≤ j. The partial sums can land far outside [0, 1], yet the bounds still hold: above",
        "P(⋃ Aᵢ) at odd steps and below it at even steps."
      ),
      "Boole and Bonferroni are duals" = paste(
        "applying Boole to A₁ᶜ, …, Aₖᶜ and invoking De Morgan turns P(⋃ Aᵢᶜ) ≤ Σ(1 − P(Aᵢ)) directly into",
        "P(⋂ Aᵢ) ≥ Σ P(Aᵢ) − (k − 1) (Casella and Berger, eq. 1.2.10)."
      )
    )
  )
}

mod_alem_axiomas_ui <- function(id) {
  ns <- shiny::NS(id)

  bslib::layout_sidebar(
    sidebar = bslib::sidebar(
      width = 315,
      shiny::selectInput(
        ns("colecao"), tr("Coleção candidata ℬ em S = {1, 2, 3}", "Candidate collection ℬ on S = {1, 2, 3}"),
        choices = stats::setNames(names(colecoes_sigma3), purrr::map_chr(colecoes_sigma3, "rotulo")),
        selected = "gerada_1"
      ),
      shiny::hr(),
      shiny::sliderInput(
        ns("k_ev"), tr("Número de eventos (k)", "Number of events (k)"),
        min = 2, max = 8, value = 4, step = 1
      ),
      shiny::sliderInput(
        ns("p_ev"), tr("Probabilidade marginal P(Aᵢ) = p", "Marginal probability P(Aᵢ) = p"),
        min = 0.05, max = 0.98, value = 0.90, step = 0.01
      ),
      shiny::radioButtons(
        ns("regime"), tr("Dependência entre A₁, …, Aₖ", "Dependence among A₁, …, Aₖ"),
        choices = stats::setNames(
          c("independente", "disjunto", "comonotonico"),
          tr(
            c(
              "Independentes: P(⋂ Aᵢ) = p^k",
              "Sobreposição mínima (disjuntos se k·p ≤ 1)",
              "Sobreposição total (A₁ = … = Aₖ)"
            ),
            c(
              "Independent: P(⋂ Aᵢ) = p^k",
              "Minimal overlap (disjoint if k·p ≤ 1)",
              "Complete overlap (A₁ = … = Aₖ)"
            )
          )
        ),
        selected = "independente"
      )
    ),
    bslib::layout_columns(
      fill = FALSE,
      bslib::value_box(
        title = tr("Interseção P(⋂ Aᵢ) e Bonferroni", "Intersection P(⋂ Aᵢ) and Bonferroni"),
        value = shiny::textOutput(ns("vb_bonf_val")),
        shiny::textOutput(ns("vb_bonf_sub")),
        theme = "primary"
      ),
      bslib::value_box(
        title = tr("União P(⋃ Aᵢ) e cota de Boole", "Union P(⋃ Aᵢ) and Boole's bound"),
        value = shiny::textOutput(ns("vb_boole_val")),
        shiny::textOutput(ns("vb_boole_sub")),
        theme = "info"
      ),
      bslib::value_box(
        title = tr("Verificação da coleção ℬ", "Check of collection ℬ"),
        value = shiny::textOutput(ns("vb_sigma_val")),
        shiny::textOutput(ns("vb_sigma_sub")),
        theme = NULL
      )
    ),
    bslib::layout_columns(
      col_widths = bslib::breakpoints(sm = 12, lg = c(6, 6)),
      bslib::card(full_screen = TRUE, bslib::card_body(shiny::plotOutput(ns("grafico_cotas"), height = "410px"))),
      bslib::card(
        bslib::card_header(tr("Diagnóstico de σ-álgebra (Def. 1.2.1) e tabela de cotas", "σ-algebra check (Def. 1.2.1) and bounds table")),
        bslib::card_body(
          shiny::uiOutput(ns("painel_sigma")),
          shiny::hr(),
          shiny::uiOutput(ns("tabela_ie"))
        )
      )
    ),
    bslib::layout_columns(
      col_widths = bslib::breakpoints(sm = 12, lg = c(7, 5)),
      bslib::card(bslib::card_header(rotulo_entenda()), bslib::card_body(texto_alem_axiomas())),
      cartao_cuidados(tr("Cuidados", "Watch out"), cuidados_alem_axiomas())
    )
  )
}

mod_alem_axiomas_server <- function(id, modo = shiny::reactive("light")) {
  shiny::moduleServer(id, function(input, output, session) {

    col_atual <- shiny::reactive({
      shiny::req(input$colecao)
      colecoes_sigma3[[input$colecao]]
    })

    diag_sigma <- shiny::reactive({
      verificar_sigma_algebra(col_atual()$conjuntos)
    })

    cotas <- shiny::reactive({
      shiny::req(input$k_ev, input$p_ev, input$regime)
      cotas_inclusao_exclusao(input$k_ev, input$p_ev, input$regime)
    })

    output$vb_bonf_val <- shiny::renderText({
      ct <- cotas()
      sprintf("%s (≥ %s)", fmt_num(ct$p_inter_real, 4), fmt_num(ct$cota_bonferroni_util, 4))
    })

    output$vb_bonf_sub <- shiny::renderText({
      ct <- cotas()
      sprintf(
        tr("Fórmula bruta ΣP(Aᵢ) − (k−1) = %s", "Raw formula ΣP(Aᵢ) − (k−1) = %s"),
        fmt_num(ct$cota_bonferroni_bruta, 3)
      )
    })

    output$vb_boole_val <- shiny::renderText({
      ct <- cotas()
      sprintf("%s (≤ %s)", fmt_num(ct$p_uniao_real, 4), fmt_num(ct$p_boole, 4))
    })

    output$vb_boole_sub <- shiny::renderText({
      ct <- cotas()
      sprintf("P₁ = Σ P(Aᵢ) = %s", fmt_num(ct$cota_boole_bruta, 3))
    })

    output$vb_sigma_val <- shiny::renderText({
      if (diag_sigma()$valida) tr("É σ-álgebra", "Valid σ-algebra") else tr("Não é σ-álgebra", "Not a σ-algebra")
    })

    output$vb_sigma_sub <- shiny::renderText({
      sprintf(tr("%d subconjuntos em ℬ", "%d subsets in ℬ"), length(col_atual()$conjuntos))
    })

    output$painel_sigma <- shiny::renderUI({
      col <- col_atual()
      dg <- diag_sigma()
      sim <- tr("Sim", "Yes")
      nao <- tr("Não", "No")

      df <- data.frame(
        tr(
          c("1. Contém ∅ (Def. 1.2.1a)", "2. Fechada no complemento (1.2.1b)", "3. Fechada na união (1.2.1c)"),
          c("1. Contains ∅ (Def. 1.2.1a)", "2. Closed under complements (1.2.1b)", "3. Closed under unions (1.2.1c)")
        ),
        c(
          if (dg$tem_vazio) sim else nao,
          if (dg$fechada_comp) sim else nao,
          if (dg$fechada_uniao) sim else nao
        ),
        c(
          if (dg$tem_vazio) "∅ ∈ ℬ" else tr("∅ ausente", "∅ missing"),
          if (dg$fechada_comp) tr("Todo Aᶜ ∈ ℬ", "Every Aᶜ ∈ ℬ") else paste(tr("Falta:", "Missing:"), dg$exemplo_falha_comp),
          if (dg$fechada_uniao) tr("Toda A ∪ B ∈ ℬ", "Every A ∪ B ∈ ℬ") else paste(tr("Falta:", "Missing:"), dg$exemplo_falha_uniao)
        ),
        stringsAsFactors = FALSE
      )
      names(df) <- tr(c("Axioma de ℬ", "Cumpre?", "Detalhe"), c("ℬ axiom", "Holds?", "Detail"))

      shiny::tagList(
        shiny::p(class = "small mb-2", shiny::strong("ℬ = "), "{",
                 paste(purrr::map_chr(col$conjuntos, formatar_subconjunto), collapse = ", "), "}"),
        tabela_html(df, classes = c("", "", "leitura")),
        shiny::p(class = "small text-muted mt-2 mb-0", col$comentario)
      )
    })

    output$tabela_ie <- shiny::renderUI({
      ct <- cotas()
      sinais_txt <- ifelse(ct$ordens %% 2L == 1L, "+", "−")
      df <- data.frame(
        paste0("m = ", ct$ordens),
        paste0(sinais_txt, " P_", ct$ordens, " = ", fmt_num(ct$termos_p, 4)),
        fmt_num(ct$somas_parciais, 4),
        ifelse(
          ct$ordens == ct$k,
          tr("Igualdade exata", "Exact equality"),
          ifelse(ct$ordens %% 2L == 1L, tr("Cota superior (≥)", "Upper bound (≥)"), tr("Cota inferior (≤)", "Lower bound (≤)"))
        ),
        stringsAsFactors = FALSE
      )
      names(df) <- tr(
        c("Passo", "Termo de ordem m", "Soma parcial S_m", "Papel (seção 1.8.1)"),
        c("Step", "Order-m term", "Partial sum S_m", "Role (section 1.8.1)")
      )
      tabela_html(df, classes = c("", "num", "num", "leitura"))
    })

    output$grafico_cotas <- shiny::renderPlot({
      ct <- cotas()
      p_modo <- paleta_modo(modo())
      df <- data.frame(
        m = ct$ordens,
        soma = ct$somas_parciais,
        papel = ifelse(ct$ordens %% 2L == 1L, "sup", "inf")
      )

      ggplot2::ggplot(df, ggplot2::aes(x = m, y = soma)) +
        ggplot2::geom_hline(yintercept = ct$p_uniao_real, colour = cores_app$referencia, linetype = "dashed", linewidth = 0.95) +
        ggplot2::geom_line(colour = p_modo$secundario, linewidth = 0.8) +
        ggplot2::geom_point(ggplot2::aes(colour = papel), size = 3.8) +
        ggplot2::scale_colour_manual(values = c(sup = cores_app$destaque, inf = p_modo$linha)) +
        ggplot2::scale_x_continuous(breaks = ct$ordens) +
        ggplot2::scale_y_continuous(labels = rotulos_eixo()) +
        tema_grafico(modo()) +
        ggplot2::labs(
          title = tr("Cotas alternadas de inclusão-exclusão S_m", "Alternating inclusion-exclusion bounds S_m"),
          subtitle = sprintf(
            tr("Tracejado vermelho: P(⋃ Aᵢ) = %s | Azul: passos ímpares (≥) | Escuro/claro: passos pares (≤)", "Dashed red: P(⋃ Aᵢ) = %s | Blue: odd steps (≥) | Dark/light: even steps (≤)"),
            fmt_num(ct$p_uniao_real, 4)
          ),
          x = tr("Ordem de truncamento m (m = 1 é a cota de Boole)", "Truncation order m (m = 1 is Boole's bound)"),
          y = tr("Soma parcial S_m = P₁ − P₂ + … ± P_m", "Partial sum S_m = P₁ − P₂ + … ± P_m"),
          caption = tr("Casella e Berger, Teo. 1.2.11b e seção 1.8.1", "Casella and Berger, Thm. 1.2.11b and section 1.8.1")
        )
    })
  })
}
