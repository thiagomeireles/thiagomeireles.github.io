# Intervalo por postos de Agresti e Finlay (seção 5.5) para a mediana (95%, n >= 20)
ic_mediana_postos_af <- function(x) {
  n <- length(x)
  if (n < 12L) return(NULL)
  ord <- sort(x)
  idx <- (n + 1) / 2 + c(-1, 1) * sqrt(n)
  pos_inf <- max(1L, floor(idx[1]))
  pos_sup <- min(n, ceiling(idx[2]))
  list(inf = ord[pos_inf], sup = ord[pos_sup], pos = c(pos_inf, pos_sup))
}

executar_bootstrap_np <- function(x, estat = "mediana", b_rep = 1000L, gama = 0.95) {
  n <- length(x)
  b_rep <- max(50L, as.integer(b_rep))
  idx_mat <- matrix(sample.int(n, size = b_rep * n, replace = TRUE), nrow = b_rep, ncol = n)
  val_mat <- matrix(x[idx_mat], nrow = b_rep, ncol = n)

  est_boot <- calcular_estat_matriz(val_mat, estat)
  theta_hat <- calcular_estatistica_boot(x, estat)
  ep_boot <- stats::sd(est_boot)
  var_boot <- stats::var(est_boot)
  vies_boot <- mean(est_boot) - theta_hat

  alfa <- 1 - gama
  ic_perc <- stats::quantile(est_boot, probs = c(alfa / 2, 1 - alfa / 2), names = FALSE)
  z_crit <- stats::qnorm(1 - alfa / 2)
  ic_norm <- theta_hat + c(-1, 1) * z_crit * ep_boot

  # Intervalo clássico analítico quando existir fórmula padrão nos livros-base
  ic_classico <- if (identical(estat, "media") && n >= 2L) {
    ep_m <- stats::sd(x) / sqrt(n)
    t_crit <- stats::qt(1 - alfa / 2, df = n - 1L)
    list(
      metodo = tr("Clássico t: x̄ ± t · s/√n", "Classical t: x̄ ± t · s/√n"),
      ep = ep_m,
      inf = theta_hat - t_crit * ep_m,
      sup = theta_hat + t_crit * ep_m
    )
  } else if (identical(estat, "mediana") && abs(gama - 0.95) < 1e-6 && n >= 20L) {
    postos <- ic_mediana_postos_af(x)
    list(
      metodo = sprintf(
        tr("Postos (Agresti e Finlay 5.5): x_(%d) a x_(%d)", "Order ranks (Agresti and Finlay 5.5): x_(%d) to x_(%d)"),
        postos$pos[1], postos$pos[2]
      ),
      ep = NA_real_,
      inf = postos$inf,
      sup = postos$sup
    )
  } else {
    NULL
  }

  # Guarda as primeiras 20 reamostras (índices) para inspeção individual na UI
  n_guardar <- min(20L, b_rep)
  idx_guardados <- idx_mat[seq_len(n_guardar), , drop = FALSE]

  list(
    x = x, n = n, b_rep = b_rep, gama = gama, estat = estat,
    theta_hat = theta_hat, est_boot = est_boot,
    ep_boot = ep_boot, var_boot = var_boot, vies_boot = vies_boot,
    ic_perc = ic_perc, ic_norm = ic_norm, ic_classico = ic_classico,
    idx_guardados = idx_guardados,
    prop_fora_teo = (1 - 1 / n)^n
  )
}

# Aba 4 — Caso 1: Bootstrap vs. Método Delta para p(1 - p) (Casella e Berger Exs. 10.1.15, 10.1.20 e 10.1.21)
var_exata_p1mp <- function(n, p) {
  ks <- 0:n
  probs <- stats::dbinom(ks, size = n, prob = p)
  ph <- ks / n
  tau_hat <- ph * (1 - ph)
  media_tau <- sum(probs * tau_hat)
  sum(probs * (tau_hat - media_tau)^2)
}

simular_delta_boot_bernoulli <- function(n = 24L, p_obs_sucessos = 12L, b_rep = 1000L) {
  n <- max(6L, as.integer(n))
  y <- min(max(0L, as.integer(p_obs_sucessos)), n)
  phat <- y / n
  amostra <- c(rep(1L, y), rep(0L, n - y))

  # Reamostras de uma Bernoulli(phat) equivalem a K* ~ Binomial(n, phat)
  k_star <- stats::rbinom(b_rep, size = n, prob = phat)
  ph_star <- k_star / n
  tau_star <- ph_star * (1 - ph_star)

  var_boot <- stats::var(tau_star)
  var_delta1 <- phat * (1 - phat) * (1 - 2 * phat)^2 / n
  var_delta2 <- 2 * (phat * (1 - phat) / n)^2
  var_verdadeira <- var_exata_p1mp(n, phat)

  grade_p <- seq(0.02, 0.98, by = 0.02)
  curva <- data.frame(
    p = grade_p,
    verdadeira = purrr::map_dbl(grade_p, \(pr) var_exata_p1mp(n, pr)),
    delta1 = grade_p * (1 - grade_p) * (1 - 2 * grade_p)^2 / n,
    boot_esperada = purrr::map_dbl(grade_p, \(pr) {
      # E_p[Var*(tau_hat)] exata sobre todos os k = 0..n, usando Var*(tau_hat | phat = k/n)
      ks <- 0:n
      pesos <- stats::dbinom(ks, size = n, prob = pr)
      vars_cond <- purrr::map_dbl(ks / n, \(pk) var_exata_p1mp(n, pk))
      sum(pesos * vars_cond)
    })
  )

  list(
    n = n, y = y, phat = phat, tau_hat = phat * (1 - phat),
    tau_star = tau_star, var_boot = var_boot,
    var_delta1 = var_delta1, var_delta2 = var_delta2,
    var_verdadeira = var_verdadeira, curva = curva
  )
}

# Aba 4 — Caso 2: Bootstrap paramétrico vs. não paramétrico para S² (Casella e Berger Ex. 10.1.22)
simular_boot_parametrico_s2 <- function(fonte = c("cb1022", "normal", "t5"), n = 15L, b_rep = 1000L) {
  fonte <- match.arg(fonte)
  if (identical(fonte, "cb1022")) {
    x <- ex_cb_1022
    n_ef <- length(x)
    var_real_s2 <- 2 * (4^2) / (n_ef - 1L)
  } else if (identical(fonte, "normal")) {
    n_ef <- max(6L, as.integer(n))
    x <- stats::rnorm(n_ef, mean = 3, sd = 2)
    var_real_s2 <- 2 * (4^2) / (n_ef - 1L)
  } else {
    # t com 5 gl reescalada para Var(X) = 4: curtose em excesso gama2 = 6/(5-4) = 6
    # Var(S²) = (1/n) * [mu_4 - ((n - 3)/(n - 1)) * sigma^4], com mu_4 = (3 + 6) * 16 = 144
    n_ef <- max(6L, as.integer(n))
    x <- 3 + stats::rt(n_ef, df = 5) * sqrt(4 * 3 / 5)
    sigma2 <- 4
    mu4 <- 9 * (sigma2^2)
    var_real_s2 <- (mu4 - ((n_ef - 3) / (n_ef - 1)) * (sigma2^2)) / n_ef
  }

  xbar <- mean(x)
  s2 <- stats::var(x)

  # Bootstrap paramétrico sob suposição normal: X*_i ~ N(x̄, s²)
  mat_param <- matrix(stats::rnorm(b_rep * n_ef, mean = xbar, sd = sqrt(s2)), nrow = b_rep, ncol = n_ef)
  s2_param <- calcular_estat_matriz(mat_param, "dp")^2

  # Bootstrap não paramétrico: reamostra de x com reposição
  idx_np <- matrix(sample.int(n_ef, size = b_rep * n_ef, replace = TRUE), nrow = b_rep, ncol = n_ef)
  mat_np <- matrix(x[idx_np], nrow = b_rep, ncol = n_ef)
  s2_np <- calcular_estat_matriz(mat_np, "dp")^2

  # Estimativa analítica normal por plug-in: 2 * (s²)² / (n - 1) (Ex. 10.1.22 usa s² como plug-in)
  var_formula_normal <- 2 * (s2^2) / (n_ef - 1L)

  list(
    fonte = fonte, x = x, n = n_ef, xbar = xbar, s2 = s2,
    s2_param = s2_param, s2_np = s2_np,
    var_param = stats::var(s2_param),
    var_np = stats::var(s2_np),
    var_formula_normal = var_formula_normal,
    var_real_s2 = var_real_s2
  )
}

# Aba 4 — Caso 3: Falha na fronteira U(0, θ) com θ̂ = X_(n) (Miscellanea 10.6.2 e 10.6.3)
simular_falha_uniforme <- function(n = 25L, theta = 10, b_rep = 1500L) {
  n <- max(5L, as.integer(n))
  x <- stats::runif(n, min = 0, max = theta)
  x_max <- max(x)

  # Reamostras não paramétricas
  idx_np <- matrix(sample.int(n, size = b_rep * n, replace = TRUE), nrow = b_rep, ncol = n)
  mat_np <- matrix(x[idx_np], nrow = b_rep, ncol = n)
  max_np <- purrr::map_dbl(seq_len(b_rep), \(i) max(mat_np[i, ]))

  # Reamostras paramétricas plug-in: X*_i ~ U(0, θ̂)
  max_param <- x_max * (stats::runif(b_rep)^(1 / n))

  # Amostras verdadeiras da população U(0, θ) para comparação direta
  max_real <- theta * (stats::runif(b_rep)^(1 / n))

  massa_atomo_teo <- 1 - (1 - 1 / n)^n
  massa_atomo_emp <- mean(abs(max_np - x_max) < 1e-12)
  ep_real <- theta * sqrt(n / ((n + 2) * (n + 1)^2))

  list(
    n = n, theta = theta, x = x, x_max = x_max,
    max_np = max_np, max_param = max_param, max_real = max_real,
    massa_atomo_teo = massa_atomo_teo,
    massa_atomo_emp = massa_atomo_emp,
    ic_perc_np = stats::quantile(max_np, probs = c(0.025, 0.975), names = FALSE),
    ep_np = stats::sd(max_np),
    ep_param = stats::sd(max_param),
    ep_real = ep_real
  )
}
