# Gerador congruencial linear puro (sem tocar no .Random.seed global da sessão)
gerar_congruencial <- function(n, semente = 2026, a = 16807, c_inc = 0, m = 2147483647) {
  n <- max(2L, as.integer(n))
  x0 <- abs(round(semente)) %% m
  if (x0 == 0 && c_inc == 0) x0 <- 1
  xs <- purrr::accumulate(seq_len(n), \(x, ...) (a * x + c_inc) %% m, .init = x0)[-1]
  u <- xs / m
  list(x = xs, u = u, distintos = length(unique(xs)))
}

