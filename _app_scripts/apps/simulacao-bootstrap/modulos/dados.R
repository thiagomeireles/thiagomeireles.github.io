calcular_estatistica_boot <- function(x, estat = "mediana") {
  switch(estat,
    media   = mean(x),
    mediana = stats::median(x),
    dp      = stats::sd(x),
    cv      = stats::sd(x) / mean(x)
  )
}

calcular_estat_matriz <- function(mat, estat = "mediana") {
  n_col <- ncol(mat)
  if (identical(estat, "media")) return(rowMeans(mat))
  if (identical(estat, "dp")) {
    meds <- rowMeans(mat)
    return(sqrt(pmax(0, (rowSums(mat^2) - n_col * meds^2) / (n_col - 1L))))
  }
  if (identical(estat, "cv")) {
    meds <- rowMeans(mat)
    dps <- sqrt(pmax(0, (rowSums(mat^2) - n_col * meds^2) / (n_col - 1L)))
    return(dps / meds)
  }
  purrr::map_dbl(seq_len(nrow(mat)), \(i) stats::median(mat[i, ]))
}

